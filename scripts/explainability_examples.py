"""
Explainability and provenance: run the grounded pipeline on questions and write, for each, the retrieved
graph facts grouped as explicit / inferred / reasoning path / scenario, the LLM's generated answer and the
facts it cites. Also runs one question with insufficient graph evidence.

Usage:  python scripts/explainability_examples.py
Output: Results/iteration2/explainability_examples.md
"""
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from qualifypath import qa  # noqa: E402
from qualifypath.kg import EXPLICIT, INFERRED  # noqa: E402

QUESTIONS = [
    ("Inferred knowledge via a property chain (CQ13)", "At which venues has Rajasthan Royals played in IPL 2026 so far?"),
    ("Rule-derived knowledge and multi-hop reasoning (CQ5-CQ7)", "Can Lucknow Super Giants still qualify for the top 4, and what do they need?"),
    ("Hypothetical scenario (CQ10)", "If Kolkata Knight Riders lose their last league match, which teams are certain to finish above them?"),
    ("Insufficient evidence", "Who is the top run scorer for Rajasthan Royals in IPL 2026?"),
]
GROUPS = [("Explicit knowledge (stored in the graph)", [EXPLICIT]),
          ("Inferred knowledge (OWL 2 RL reasoning / SPARQL rules R1-R7)", [INFERRED, "rule-derived"]),
          ("Multi-hop reasoning paths over explicit + inferred facts", ["reasoning path"]),
          ("Hypothetical scenario (not a fact)", ["scenario"])]

out = ["# Explainability and provenance examples", "",
       "Generated by `scripts/explainability_examples.py`. Each example separates explicit knowledge, inferred "
       "knowledge and the LLM's generated text. Fact IDs [F#] are the ones the answer cites.", ""]
for i, (title, q) in enumerate(QUESTIONS, 1):
    a = qa.ask_grounded(q)
    time.sleep(2)
    cited = {f.id for f in a.cited}
    out += [f"## Example {i}: {title}", "", f"**Question:** {q}", "",
            f"**Linked entities:** {', '.join(qa.retriever().kg.label(t) for t in a.retrieval.teams) or 'none'}; "
            f"**intents:** {', '.join(a.retrieval.intents) or 'none'}; **facts retrieved:** {len(a.retrieval.facts)}", ""]
    for name, kinds in GROUPS:
        facts = [f for f in a.retrieval.facts if f.kind in kinds]
        if not facts:
            continue
        out.append(f"**{name}**")
        out.append("")
        for f in facts[:12]:
            out.append(f"- [{f.id}]{' (cited)' if f.id in cited else ''} {f.text}")
        if len(facts) > 12:
            out.append(f"- ... {len(facts) - 12} more")
        out.append("")
    out += ["**Generated text (LLM answer):**", "", "> " + a.answer.replace("\n", "\n> "), "",
            f"**Supporting evidence cited:** {', '.join(sorted(cited, key=lambda x: int(x[1:]))) or 'none'}"
            + (f" — {a.warning}" if a.warning else ""), ""]
    print(f"Example {i}: {len(a.retrieval.facts)} facts, cited {sorted(cited)}")
(ROOT / "Results" / "iteration2" / "explainability_examples.md").write_text("\n".join(out), encoding="utf-8")
