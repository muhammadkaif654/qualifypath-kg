def stats(items: list[tuple[str, str, str]]):
    """Joined stat strip: (label, value, colour class g|c|a|'')."""
    cells = "".join(f"<div class='qp-stat'><div class='v {c}'>{v}</div><div class='l'>{l}</div></div>" for l, v, c in items)
    st.markdown(f"<div class='qp-stats qp-fade'>{cells}</div>", unsafe_allow_html=True)


