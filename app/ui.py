def cite(text: str) -> str:
    """Highlight [F12]-style citations inside markdown answer text."""
    return re.sub(r"\[\s*(F\d+(?:\s*,\s*F\d+)*)\s*\]",
                  lambda m: " ".join(f"<span class='qp-cite'>{x.strip()}</span>" for x in m.group(1).split(",")),
                  text)


