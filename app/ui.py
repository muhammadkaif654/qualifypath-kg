def path_graph(kg_: KG, paths, max_paths: int = 12) -> str:
    """Graphviz DOT for reasoning paths: nodes are entities/values, edges coloured by provenance."""
    colours = {"explicit": "#059669", "inferred": "#2563eb", "rule-derived": "#7c3aed"}
    nodes, edges = {}, {}

    def nid(x):
        key = str(x)
        if key not in nodes:
            label = kg_.label(x)
            if len(label) > 34:
                label = label[:32] + "…"
            nodes[key] = (f"n{len(nodes)}", label, "Literal" in type(x).__name__)
        return nodes[key][0]

    for path in paths[:max_paths]:
        for h in path:
            a, b = nid(h.s), nid(h.o)
            pred = str(h.p).rsplit("#", 1)[-1]
            edges[(a, b, pred)] = colours.get(h.provenance.split(" ")[0], "#64748b")
    lines = ['digraph G { rankdir=LR; bgcolor="transparent"; pad=0.2; nodesep=0.25; ranksep=0.5;',
             'node [shape=box, style="rounded,filled", fontname="Helvetica", fontsize=10, '
             'fillcolor="#eef2ff", color="#6366f1"]; edge [fontname="Helvetica", fontsize=8];']
    for _, (n, label, literal) in nodes.items():
        extra = ', fillcolor="#fef3c7", color="#d97706", shape=ellipse' if literal else ""
        lines.append(f'{n} [label="{label.replace(chr(34), "")}"{extra}];')
    for (a, b, pred), colour in edges.items():
        lines.append(f'{a} -> {b} [label="{pred}", color="{colour}", fontcolor="{colour}", penwidth=1.6];')
    lines.append("}")
    return "\n".join(lines)
