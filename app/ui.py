@st.cache_resource(show_spinner="Loading the knowledge graph, running OWL 2 RL reasoning and rules R1–R7…")
def kg() -> KG:
    return load_kg()


@st.cache_resource(show_spinner=False)
def retriever():
    kg()
    return qa.retriever()


@st.cache_resource(show_spinner=False)
def reasoner() -> MultiHopReasoner:
    return MultiHopReasoner(kg())


def badge(kind: str) -> str:
    label, colour = KIND.get(kind, (kind, "#64748b"))
    return f"<span class='qp-badge' style='background:{colour}'>{html.escape(label)}</span>"


def hero(title: str, subtitle: str, steps: list[str] | None = None):
    flow = ""
    if steps:
        parts = []
        for i, s in enumerate(steps):
            parts.append(f"<span class='qp-step'>{html.escape(s)}</span>")
            if i < len(steps) - 1:
                parts.append("<span class='qp-arrow'>➜</span>")
        flow = f"<div class='qp-flow'>{''.join(parts)}</div>"
    st.markdown(f"<div class='qp-hero'><h1>{title}</h1><p>{subtitle}</p>{flow}</div>", unsafe_allow_html=True)


def metrics(items: list[tuple[str, str]]):
    cols = st.columns(len(items))
    for c, (label, value) in zip(cols, items):
        c.markdown(f"<div class='qp-metric'><div class='v'>{value}</div><div class='l'>{label}</div></div>",
                   unsafe_allow_html=True)


def cite(text: str) -> str:
    """Highlight [F12]-style citations inside markdown answer text."""
    return re.sub(r"\[\s*(F\d+(?:\s*,\s*F\d+)*)\s*\]",
                  lambda m: " ".join(f"<span class='qp-cite'>{x.strip()}</span>" for x in m.group(1).split(",")),
                  text)


def fact_card(f, cited: bool = False) -> str:
    star = " <span class='qp-muted'>· cited</span>" if cited else ""
    return (f"<div class='qp-fact'>{badge(f.kind)}<span class='id'>{f.id}</span>"
            f"{html.escape(f.text)}{star}</div>")


