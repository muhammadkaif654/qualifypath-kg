def status_pill(status: str) -> str:
    s = status.lower()
    cls = "q" if "qualif" in s else "e" if "elimin" in s else "c" if "contention" in s else "n"
    text = {"q": "Qualified", "e": "Eliminated", "c": "In contention"}.get(cls, status)
    return f"<span class='qp-pill {cls}'>{text}</span>"


