def path_graph(kg_: KG, paths, max_paths: int = 12) -> str:
    """Graphviz DOT for reasoning paths: nodes are entities/values, edges coloured by provenance."""
    colours = {"explicit": "#10b981", "inferred": "#60a5fa", "rule-derived": "#c084fc"}
    nodes, edges = {}, {}

    def nid(x):
        key = str(x)
        if key not in nodes:
            label = kg_.label(x)
            if len(label) > 34:
                label = label[:32] + "…"
            nodes[key] = (f"n{len(nodes)}", label, "Literal" in type(x).__name__)
        return nodes[key][0]

    for path in paths[:max_paths]:
        for h in path:
            a, b = nid(h.s), nid(h.o)
            pred = str(h.p).rsplit("#", 1)[-1]
            edges[(a, b, pred)] = colours.get(h.provenance.split(" ")[0], "#94a3b8")
    lines = ['digraph G { rankdir=LR; bgcolor="transparent"; pad=0.2; nodesep=0.25; ranksep=0.5; size="13,7";',
             'node [shape=box, style="rounded,filled", fontname="Helvetica", fontsize=10, '
             'fillcolor="#1e293b", color="#6366f1", fontcolor="#e2e8f0"]; edge [fontname="Helvetica", fontsize=8];']
    for _, (n, label, literal) in nodes.items():
        short = label if label in TEAMS else None
        if literal:
            extra = ', fillcolor="#3b2a05", color="#f59e0b", fontcolor="#fde68a", shape=ellipse'
        elif short:
            _, bg, ring, fg = TEAMS[short]
            extra = f', shape=circle, fillcolor="{bg}", color="{ring}", fontcolor="{fg}", penwidth=2.5, fontsize=11'
        else:
            extra = ""
        lines.append(f'{n} [label="{label.replace(chr(34), "")}"{extra}];')
    for (a, b, pred), colour in edges.items():
        lines.append(f'{a} -> {b} [label="{pred}", color="{colour}", fontcolor="{colour}", penwidth=1.6];')
    lines.append("}")
    return "\n".join(lines)
